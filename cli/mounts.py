"""User-chosen host folders exposed to the sandbox as /mounts/<name>.

Stored in %APPDATA%\\AgentOS\\mounts.json; rendered to docker-compose.mounts.yml (JSON is valid YAML) next to
docker-compose.yml. The runner gets the requested mode; the gateway always gets a read-only view.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from .paths import MOUNTS_FILE, ensure_appdata

OVERRIDE_NAME = "docker-compose.mounts.yml"
_NAME_RE = re.compile(r"^[a-z0-9][a-z0-9_-]{0,40}$")


def load() -> list[dict]:
    try:
        return json.loads(MOUNTS_FILE.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []


def _save(items: list[dict]) -> None:
    ensure_appdata()
    MOUNTS_FILE.write_text(json.dumps(items, indent=2), encoding="utf-8")


def slug(text: str) -> str:
    s = re.sub(r"[^a-z0-9_-]+", "-", text.lower()).strip("-")[:40]
    return s or "mount"


def add(host_path: str, rw: bool = False, name: str | None = None) -> dict:
    p = Path(host_path).expanduser().resolve()
    if not p.is_dir():
        raise ValueError(f"not a folder: {p}")
    if p == Path(p.anchor) or p == Path.home():
        raise ValueError(f"refusing to mount a whole drive or your home folder: {p}")
    name = slug(name or p.name)
    if not _NAME_RE.match(name):
        raise ValueError(f"invalid mount name: {name}")
    items = [m for m in load() if m["name"] != name]
    item = {"name": name, "host_path": str(p), "mode": "rw" if rw else "ro", "container_path": f"/mounts/{name}"}
    items.append(item)
    _save(items)
    return item


def remove(name: str) -> bool:
    items = load()
    rest = [m for m in items if m["name"] != name]
    _save(rest)
    return len(rest) != len(items)


def render_override(repo: Path) -> Path | None:
    """Write (or delete) docker-compose.mounts.yml. Returns its path when there is at least one mount."""
    target = repo / OVERRIDE_NAME
    items = load()
    if not items:
        if target.exists():
            target.unlink()
        return None

    def vol(m: dict, read_only: bool) -> dict:
        return {"type": "bind", "source": m["host_path"], "target": m["container_path"], "read_only": read_only}

    doc = {"services": {
        "runner": {"volumes": [vol(m, m["mode"] != "rw") for m in items]},
        "gateway": {"volumes": [vol(m, True) for m in items]},
    }}
    target.write_text("# generated by `agentos mount` — do not edit\n" + json.dumps(doc, indent=2), encoding="utf-8")
    return target
