SAFE_TEMPLATE = '''"""Generated by AgentOS Agent Builder: {name}.
Pure function: run(input) -> dict. Executed only inside the sandboxed runner."""
import re
import statistics
from collections import Counter

PURPOSE = {purpose!r}
KEYWORDS = {keywords!r}


def _numbers(text):
    return [float(x) for x in re.findall(r"-?\\d+(?:\\.\\d+)?", text)]


def _items(text):
    """Parse lines like 'topic: 12/20', 'topic - 5', 'topic,7' into (label, value, total)."""
    out = []
    for line in text.splitlines():
        m = re.match(r"\\s*([A-Za-z][\\w +#./-]*?)\\s*[:,=\\-]\\s*(\\d+(?:\\.\\d+)?)(?:\\s*/\\s*(\\d+(?:\\.\\d+)?))?", line)
        if m:
            total = float(m.group(3)) if m.group(3) else None
            out.append((m.group(1).strip(), float(m.group(2)), total))
    return out


def run(input):
    text = str(input.get("text") or input.get("task") or "")
    for item in input.get("context") or []:
        if isinstance(item, dict):
            text += "\\n" + str(item.get("result", "")) + "\\n" + str(item.get("summary", ""))
    items = _items(text)
    nums = _numbers(text)
    words = Counter(w for w in re.findall(r"[a-z]{{4,}}", text.lower()) if w in KEYWORDS)
    findings = []
    recommendations = []
    if items:
        scored = []
        for label, value, total in items:
            ratio = value / total if total else None
            scored.append({{"label": label, "value": value, "total": total,
                           "ratio": round(ratio, 3) if ratio is not None else None}})
        with_ratio = [s for s in scored if s["ratio"] is not None]
        ranked = sorted(with_ratio or scored, key=lambda s: s["ratio"] if s["ratio"] is not None else s["value"])
        weakest = ranked[:3]
        strongest = ranked[-3:][::-1]
        findings.append("Weakest: " + ", ".join(s["label"] for s in weakest))
        findings.append("Strongest: " + ", ".join(s["label"] for s in strongest))
        plan = []
        for i, s in enumerate(weakest):
            plan.append({{"focus": s["label"], "sessions": 3 - i, "goal": "raise completion by 20%"}})
        recommendations = ["Focus on " + s["label"] for s in weakest]
        result = {{"items": scored, "weakest": weakest, "strongest": strongest, "plan": plan}}
    elif nums:
        result = {{"count": len(nums), "mean": round(statistics.mean(nums), 3), "min": min(nums), "max": max(nums)}}
        findings.append("Analysed %d numeric values" % len(nums))
    else:
        result = {{"note": "No structured data found; provide lines like 'topic: solved/total'."}}
        findings.append("No structured data in input")
    summary = PURPOSE + " — " + "; ".join(findings)
    return {{"summary": summary, "result": result, "recommendations": recommendations,
            "keywords_seen": dict(words)}}
'''


