def validate_code(code: str) -> list[str]:
    """AST policy for generated logic.py. Returns a list of violations (empty == ok)."""
    errs: list[str] = []
    try:
        tree = ast.parse(code)
    except SyntaxError as e:
        return [f"syntax error line {e.lineno}: {e.msg}"]
    has_run = False
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for a in node.names:
                if a.name.split(".")[0] not in ALLOWED_IMPORTS:
                    errs.append(f"import not allowed: {a.name}")
        elif isinstance(node, ast.ImportFrom):
            if (node.module or "").split(".")[0] not in ALLOWED_IMPORTS or node.level:
                errs.append(f"import not allowed: from {node.module}")
        elif isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in BANNED_CALLS:
            errs.append(f"call not allowed: {node.func.id}()")
        elif isinstance(node, ast.Name) and node.id in BANNED_CALLS | {"__builtins__"}:
            errs.append(f"name not allowed: {node.id}")
        elif isinstance(node, ast.Attribute) and node.attr.startswith("__"):
            errs.append(f"dunder attribute not allowed: .{node.attr}")
        elif isinstance(node, (ast.Global, ast.Nonlocal)):
            errs.append("global/nonlocal not allowed")
        elif isinstance(node, ast.FunctionDef) and node.name == "run" and node in tree.body:
            has_run = len(node.args.args) == 1
    if not has_run:
        errs.append("missing top-level `def run(input)` with exactly one argument")
    return sorted(set(errs))


def validate_manifest(d: dict) -> tuple[AgentSpec | None, list[str]]:
    errs = []
    try:
        spec = AgentSpec.model_validate(d)
    except Exception as e:  # noqa: BLE001
        return None, [f"manifest schema: {e}"[:500]]
    if not re.fullmatch(r"[a-z][a-z0-9_]{2,48}", spec.id):
        errs.append("id must be snake_case, 3-49 chars")
    if spec.graph not in ARCHETYPES or spec.graph in NON_BUILDABLE:
        errs.append(f"unknown/forbidden archetype {spec.graph}")
    unknown = [t for t in spec.tools if TOOLS and t not in TOOLS]
    if unknown:
        errs.append(f"unknown tools: {unknown}")
    p = spec.permissions
    if p.desktop or p.browser == "host":
        errs.append("generated agents may not request desktop or host-browser access")
    if any(g.path not in ("/workspace", "/shared") and not g.path.startswith(("/workspace/", "/shared/", "/mounts/"))
           for g in p.fs):
        errs.append("fs grants must be under /workspace, /shared or /mounts")
    return spec, errs


