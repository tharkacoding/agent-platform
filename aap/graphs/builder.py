def understand_spec(state: BuilderState, config) -> dict:
    ctx = get_ctx(config)
    ctx.node("understand_spec", "Understanding what the new agent must do")
    req = c.instruction(state)
    # the Main Agent sends "Build a new reusable agent.\nName idea: …\nPurpose: <user request>…" — use the purpose line
    m = re.search(r"(?im)^(?:purpose|original user request):\s*(.+)$", req)
    src = m.group(1) if m else req
    core = re.sub(r"^.*?\b(?:agent|bot|assistant)\b\s*(?:that|which|to|for|who)?\s*", "", src, flags=re.I) or src
    kws = c.keywords(core, 8)
    verbs = {"automatically", "personal", "weekly", "daily", "monitors", "creates", "analyzes", "analyses", "makes",
             "generates", "tracks", "builds", "helps", "manages", "checks", "writes", "finds"}
    name_words = [w for w in kws if w not in verbs][:3]
    fb_name = " ".join(w.capitalize() for w in name_words) + " Agent" if name_words else "Custom Agent"
    logic_words = {"analy", "track", "progr", "plan", "score", "calcu", "monit", "stati", "measu", "recom", "weak"}
    fb = {"name": fb_name, "goal": core.strip()[:300] or req[:300], "inputs": ["free text or structured data"],
          "outputs": ["summary", "structured result", "recommendations"],
          "capabilities": [k.replace("-", "_") for k in kws[:6]],
          "needs_custom_logic": any(w[:5] in logic_words for w in kws), "example_task": f"{core.strip()[:200]}"}
    spec_req = c.ask_json(ctx, (
        "You are the Agent Builder. Turn the request into an agent specification. Return JSON with keys: "
        "name (Title Case, ends with 'Agent'), goal, inputs[], outputs[], capabilities[] (snake_case), "
        "needs_custom_logic (true if deterministic computation/parsing in Python would help), "
        "example_task (a realistic task to smoke-test the agent, with small inline sample data), "
        "new_tools (list of short purposes for tools that DON'T exist yet but the agent needs; [] if existing tools "
        "suffice)."),
        f"Request:\n{req}\n\nExisting tools: {', '.join(sorted(TOOLS))[:1200]}\n\nContext:\n{c.context_text(state)}",
        fallback=lambda: fb,
        validate=lambda d: bool(d.get("name")) and isinstance(d.get("capabilities"), list), role="builder")
    for k, v in fb.items():
        spec_req.setdefault(k, v)
    c.emit_plan(ctx, {"spec": spec_req}, "Agent specification")
    fa = c.budget(ctx).get("fix_attempts", cfg.MAX_BUILD_ATTEMPTS)
    return {"request": req, "spec_req": spec_req, "attempts": 0, "log": [],
            "max_attempts": max(1, min(cfg.MAX_BUILD_ATTEMPTS, int(fa)))}


def inspect_registry(state: BuilderState, config) -> dict:
    ctx = get_ctx(config)
    ctx.node("inspect_registry", "Looking for similar existing agents")
    from ..registry import tokens
    want = tokens(" ".join([state["spec_req"].get("goal", ""), " ".join(state["spec_req"].get("capabilities", []))]))
    sims = []
    for s in ctx.runtime.list_specs():
        if s.type == "system":
            continue
        have = tokens(f"{s.name} {s.description} {' '.join(s.capabilities)}")
        score = len(want & have)
        if score:
            sims.append({"id": s.id, "name": s.name, "type": s.type, "score": score, "graph": s.graph,
                         "capabilities": s.capabilities[:8], "description": s.description[:160]})
    sims.sort(key=lambda x: -x["score"])
    ctx.emit("Similar agents: " + (", ".join(f"{s['name']}({s['score']})" for s in sims[:5]) or "none"))
    return {"similar": sims[:8]}


def select_components(state: BuilderState, config) -> dict:
    ctx = get_ctx(config)
    ctx.node("select_components", "Selecting reusable agents, tools and skills")
    cand = [s for s in state.get("similar", []) if s["type"] in ("prebuilt", "custom", "user", "imported")]
    fb = {"uses": [s["id"] for s in cand[:2] if s["score"] >= 2], "reason": "highest capability overlap"}
    ids = {s["id"] for s in cand}
    sel = c.ask_json(ctx, (
        "Choose which EXISTING agents the new agent should delegate to (reuse instead of reinventing). "
        "Return {\"uses\": [agent ids from the candidates, max 4], \"reason\": str}. Empty list is fine."),
        f"New agent: {json.dumps(state['spec_req'])}\nCandidates: {json.dumps(cand[:10])}",
        fallback=lambda: fb, validate=lambda d: isinstance(d.get("uses"), list), role="builder")
    uses = [u for u in sel.get("uses", []) if u in ids][:4]
    return {"components": {"uses": uses, "reason": sel.get("reason", "")}}


def design(state: BuilderState, config) -> dict:
    ctx = get_ctx(config)
    ctx.node("design", "Designing manifest, workflow and permissions")
    sr, comp = state["spec_req"], state["components"]
    buildable = sorted(k for k in ARCHETYPES if k not in NON_BUILDABLE)
    descs = {k: ARCHETYPES[k].description for k in buildable}
    text = (sr.get("goal", "") + " " + state["request"]).lower()
    if comp["uses"] and len(comp["uses"]) >= 2 and not sr.get("needs_custom_logic"):
        fb_arch = "composite"
    elif sr.get("needs_custom_logic"):
        fb_arch = "generic"
    elif any(w in text for w in ("research", "find out", "investigate")):
        fb_arch = "research"
    elif any(w in text for w in ("csv", "dataset", "statistic")):
        fb_arch = "data"
    elif any(w in text for w in ("teach", "lesson", "quiz", "explain")):
        fb_arch = "teacher"
    elif any(w in text for w in ("write", "essay", "blog", "email")):
        fb_arch = "writer"
    elif "plan" in text:
        fb_arch = "planner"
    else:
        fb_arch = "generic"
    d = c.ask_json(ctx, (
        f"Pick the workflow archetype for the new agent from {buildable}. Descriptions: {json.dumps(descs)}. "
        "Return {\"graph\": key, \"icon\": one emoji, \"category\": short category, \"description\": one sentence}."),
        json.dumps(sr), fallback=lambda: {"graph": fb_arch, "icon": "✨", "category": "Custom",
                                          "description": sr.get("goal", "")[:200]},
        validate=lambda x: x.get("graph") in buildable, role="builder")
    graph = d["graph"]
    base_id = c.slugify(sr["name"].replace(" Agent", "").replace(" agent", ""), 40) + "_agent"
    existing = ctx.runtime.get_spec(base_id)
    agent_id = base_id if (existing is None or existing.type in ("custom", "user")) else f"{base_id}_custom"
    tools = list(ARCHETYPE_TOOLS.get(graph, []))
    if sr.get("needs_custom_logic"):
        tools.append("custom_logic")
    # self-extension: if the agent needs a capability no existing tool provides, order it from the Tool Builder
    for need in (sr.get("new_tools") or [])[:2]:
        if isinstance(need, dict):
            need = need.get("purpose") or need.get("description") or need.get("name") or ""
        if not str(need).strip():
            continue
        rep = ctx.delegate("tool_builder_agent", f"Create a tool: {need}")
        made = re.search(r"New tool \*\*(\w+)\*\*", rep.summary or "")
        if rep.status == "success" and made:
            tools.append(made.group(1))
            ctx.emit(f"Tool Builder created '{made.group(1)}' for the new agent")
    tools = [t for t in dict.fromkeys(tools) if not TOOLS or t in TOOLS]
    perms = Permissions(fs=[{"path": "/workspace", "mode": "rw" if graph in ("coding", "testing") else "ro"}],
                        network=["*"] if graph == "research" else [],
                        shell=graph in ("coding", "testing", "debug"),
                        browser="sandbox" if graph == "browser" else "none", desktop=False)
    manifest = {"id": agent_id, "name": sr["name"], "type": "custom", "category": d.get("category") or "Custom",
                "icon": d.get("icon") or "✨", "description": d.get("description") or sr.get("goal", ""),
                "capabilities": [c.slugify(x, 30) for x in sr.get("capabilities", [])][:10],
                "tools": tools, "uses": comp["uses"], "permissions": perms.model_dump(), "graph": graph,
                "config": {"example_task": sr.get("example_task", ""), "has_logic": bool(sr.get("needs_custom_logic"))},
                "status": "draft", "created_by": "agent_builder", "version": "1.0"}
    c.emit_plan(ctx, {"manifest": manifest}, "Agent design")
    return {"design": manifest}


def generate_prompts(state: BuilderState, config) -> dict:
    ctx = get_ctx(config)
    ctx.node("generate_prompts", "Writing the system prompt")
    m, sr = state["design"], state["spec_req"]
    draft = (f"You are {m['name']}. {m['description']}\n\nGoal: {sr.get('goal')}\nInputs: {sr.get('inputs')}\n"
             f"Outputs: {sr.get('outputs')}\nCapabilities: {', '.join(m['capabilities'])}\n"
             "Always return a clear summary, structured findings, and concrete recommendations. "
             "If input data is missing, say exactly what data you need.")
    prompt = draft
    if not c.is_mock(ctx) and ctx.runtime.get_spec("writer_agent"):
        rep = c.delegate(ctx, "writer_agent",
                         "Improve this system prompt for an AI agent. Keep it under 250 words, imperative, no "
                         f"preamble. Return only the prompt.\n\n{draft}")
        if rep.get("status") != "failed" and isinstance(rep.get("result"), str) and len(rep["result"]) > 80:
            prompt = rep["result"].strip()
    return {"prompt": prompt}


def generate_code(state: BuilderState, config) -> dict:
    ctx = get_ctx(config)
    if not state["design"]["config"].get("has_logic"):
        ctx.node("generate_code", "No custom code needed (pure workflow agent)")
        return {"code": ""}
    ctx.node("generate_code", "Writing logic.py")
    sr = state["spec_req"]
    template = SAFE_TEMPLATE.format(name=state["design"]["name"], purpose=sr.get("goal", "")[:200],
                                    keywords=[k for k in c.keywords(sr.get("goal", ""), 10)])
    code = ""
    if not c.is_mock(ctx):
        txt = c.ask_text(ctx, (
            "Write logic.py for this agent: a single pure Python function `def run(input: dict) -> dict`. "
            f"input has keys text (str), task (str), context (list of report dicts). Allowed imports ONLY: "
            f"{sorted(ALLOWED_IMPORTS)}. No file/network/OS access, no eval/exec/open/getattr, no dunder attributes. "
            "Return a dict with keys summary (str), result (any JSON), recommendations (list[str]). Parse loosely "
            "formatted text robustly. Reply with one ```python code block only."),
            f"Agent spec: {json.dumps(sr)}\n\nReference implementation you may adapt:\n```python\n{template}\n```",
            fallback=lambda: "", role="builder", trim=False, min_tokens=3000)
        blocks = c.code_blocks(txt)
        code = blocks[0] if blocks else ""
    return {"code": code or template}


def generate_tests(state: BuilderState, config) -> dict:
    ctx = get_ctx(config)
    ctx.node("generate_tests", "Generating test cases")
    ex = state["spec_req"].get("example_task") or state["request"]
    fb = {"cases": [
        {"name": "example", "input": {"text": ex + "\narrays: 12/20\ndp: 3/15\ngraphs: 7/10", "task": ex, "context": []},
         "expect_keys": ["summary", "result"]},
        {"name": "empty", "input": {"text": "", "task": "", "context": []}, "expect_keys": ["summary"]}]}
    if not state.get("code"):
        return {"tests": [{"name": "workflow_smoke", "input": {"task": ex}, "expect_keys": ["summary"]}]}
    t = c.ask_json(ctx, ("Write 3 test cases for run(input) -> dict. Return {\"cases\": [{\"name\", \"input\": "
                         "{\"text\",\"task\",\"context\"}, \"expect_keys\": [keys that must be in the output]}]}. "
                         "Include an empty-input case."),
                   f"Spec: {json.dumps(state['spec_req'])}\nCode:\n{state['code'][:6000]}", fallback=lambda: fb,
                   validate=lambda d: isinstance(d.get("cases"), list) and d["cases"], role="builder")
    cases = [cs for cs in t["cases"] if isinstance(cs, dict) and isinstance(cs.get("input"), dict)][:5] or fb["cases"]
    return {"tests": cases}


def static_validation(state: BuilderState, config) -> dict:
    ctx = get_ctx(config)
    ctx.node("static_validation", "Static validation (AST policy + manifest schema)")
    errs = validate_code(state["code"]) if state.get("code") else []
    _, merrs = validate_manifest(state["design"])
    errs += merrs
    ctx.emit("Static validation passed" if not errs else f"Static validation: {len(errs)} problem(s)",
             status="done" if not errs else "failed", errors=errs)
    return {"validation": {"ok": not errs, "errors": errs}}


def run_tests(state: BuilderState, config) -> dict:
    ctx = get_ctx(config)
    ctx.node("run_tests", "Running tests in the sandbox runner")
    if not state.get("code"):
        return {"test_results": {"ok": True, "passed": 0, "failed": 0, "details": ["no code — workflow-only agent"]}}
    details, failed = [], 0
    for case in state.get("tests", []):
        r = c.tool(ctx, "run_python", code=state["code"], input=case.get("input", {}), timeout=30)
        out = r.get("output") if isinstance(r, dict) else None
        problems = []
        if not c.ok(r) or (isinstance(r, dict) and r.get("ok") is False):
            problems.append(f"execution error: {(r or {}).get('error') or (r or {}).get('stderr', '')[-400:]}")
        elif not isinstance(out, dict):
            problems.append(f"run() must return a dict, got {type(out).__name__}")
        else:
            missing = [k for k in case.get("expect_keys", []) if k not in out]
            if missing:
                problems.append(f"missing keys {missing}")
        failed += bool(problems)
        details.append({"case": case.get("name", "?"), "ok": not problems, "problems": problems,
                        "output": c.short(out, 400) if out is not None else None})
    ok_ = failed == 0 and bool(details)
    ctx.emit(f"Tests: {len(details) - failed}/{len(details)} passed", status="done" if ok_ else "failed")
    return {"test_results": {"ok": ok_, "passed": len(details) - failed, "failed": failed, "details": details}}


def debug(state: BuilderState, config) -> dict:
    ctx = get_ctx(config)
    n = state.get("attempts", 0) + 1
    ctx.node("debug", f"Debugging (attempt {n}/{_max(state)})")
    problems = state.get("validation", {}).get("errors", []) if not state.get("validation", {}).get("ok", True) \
        else [p for d in state.get("test_results", {}).get("details", []) for p in d["problems"]]
    design = dict(state["design"])
    # manifest problems: repair deterministically
    design["tools"] = [t for t in design["tools"] if not TOOLS or t in TOOLS]
    if design["graph"] not in ARCHETYPES or design["graph"] in NON_BUILDABLE:
        design["graph"] = "generic"
    code = state.get("code", "")
    if code:
        fixed = ""
        if not c.is_mock(ctx) and n < _max(state):
            txt = c.ask_text(ctx, ("Fix this logic.py so it satisfies the policy and tests. Allowed imports only: "
                                   f"{sorted(ALLOWED_IMPORTS)}. Reply with one ```python code block."),
                             f"Problems:\n{json.dumps(problems, default=str)}\n\nCode:\n```python\n{code}\n```",
                             fallback=lambda: "", role="builder", trim=False, min_tokens=3000)
            blocks = c.code_blocks(txt)
            fixed = blocks[0] if blocks else ""
        if not fixed or validate_code(fixed):
            sr = state["spec_req"]
            fixed = SAFE_TEMPLATE.format(name=design["name"], purpose=sr.get("goal", "")[:200],
                                         keywords=c.keywords(sr.get("goal", ""), 10))
            ctx.emit("Falling back to the verified safe template for logic.py")
        code = fixed
    return {"attempts": n, "code": code, "design": design}


def security_review(state: BuilderState, config) -> dict:
    ctx = get_ctx(config)
    ctx.node("security_review", "Security review of permissions and code")
    p = Permissions.model_validate(state["design"]["permissions"])
    risky = []
    if p.shell:
        risky.append("shell commands in the runner")
    if p.network:
        risky.append(f"network: {p.network}")
    if any(g.mode == "rw" for g in p.fs):
        risky.append("write access to " + ", ".join(g.path for g in p.fs if g.mode == "rw"))
    if p.browser != "none":
        risky.append(f"browser: {p.browser}")
    fb = {"risk": "medium" if risky else "low", "concerns": risky}
    rev = fb
    if not c.is_mock(ctx) and state.get("code") and c.optional_pass(ctx):
        rev = c.ask_json(ctx, "Security-review this generated agent. Return {\"risk\": low|medium|high, \"concerns\": [..]}.",
                         f"Permissions: {p.model_dump_json()}\nCode:\n{state['code'][:8000]}", fallback=lambda: fb,
                         validate=lambda d: d.get("risk") in ("low", "medium", "high"), role="builder")
    tests_ok = state.get("test_results", {}).get("ok", False) and state.get("validation", {}).get("ok", False)
    return {"security": {**rev, "permissions": p.model_dump(), "risky_permissions": risky, "tests_ok": tests_ok}}


def approval_gate(state: BuilderState, config) -> dict:
    ctx = get_ctx(config)
    sec = state["security"]
    if not sec["tests_ok"]:
        ctx.node("approval_gate", "Build failed validation/tests — saving as draft")
        return {"approved": False, "final_status": "failed"}
    p = sec["permissions"]
    needs = bool(settings.get("require_approval")) or bool(c.budget(ctx).get("require_approval")) or p.get("shell") or p.get("desktop") or \
        p.get("browser") == "host" or bool(p.get("network")) or sec.get("risk") == "high"
    if not needs:
        ctx.node("approval_gate", "Auto-approved (least-privilege, tests passed)")
        return {"approved": True, "final_status": "active"}
    ctx.node("approval_gate", "Waiting for your approval")
    try:
        ctx.approve(f"Activate new agent '{state['design']['name']}'", {
            "manifest": state["design"], "risk": sec.get("risk"), "concerns": sec.get("concerns"),
            "tests": {k: state["test_results"].get(k) for k in ("passed", "failed")},
            "code_preview": state.get("code", "")[:3000]})
        return {"approved": True, "final_status": "active"}
    except ApprovalDenied:
        ctx.emit("Rejected by user — kept as draft", status="info")
        return {"approved": False, "final_status": "draft"}


def register(state: BuilderState, config) -> dict:
    ctx = get_ctx(config)
    ctx.node("register", "Registering the agent")
    d = dict(state["design"])
    existing = ctx.runtime.get_spec(d["id"])
    if existing is not None and existing.type in ("custom", "user"):
        major, _, minor = existing.version.partition(".")
        d["version"] = f"{major}.{int(minor or 0) + 1}"
    vdir = Path(cfg.CUSTOM_AGENTS_DIR) / d["id"] / f"v{d['version']}"
    vdir.mkdir(parents=True, exist_ok=True)
    d["status"] = state.get("final_status", "draft")
    d["system_prompt"] = state.get("prompt", "")
    d["location"] = str(vdir)
    spec = AgentSpec.model_validate(d)
    files = []

    def write(name: str, content: str) -> None:
        (vdir / name).write_text(content, encoding="utf-8")
        files.append(str(vdir / name))

    try:
        import yaml  # type: ignore
        write("manifest.yaml", yaml.safe_dump(json.loads(spec.model_dump_json()), sort_keys=False, allow_unicode=True))
    except ImportError:
        write("manifest.json", spec.model_dump_json(indent=2))
    write("prompt.md", spec.system_prompt)
    if state.get("code"):
        write("logic.py", state["code"])
    write("tests.json", json.dumps({"cases": state.get("tests", []), "results": state.get("test_results")}, indent=2,
                                   default=str))
    write("README.md", f"# {spec.icon} {spec.name}\n\n{spec.description}\n\n- Version: {spec.version}\n"
                       f"- Workflow archetype: `{spec.graph}`\n- Uses: {', '.join(spec.uses) or '—'}\n"
                       f"- Tools: {', '.join(spec.tools) or '—'}\n- Status: {spec.status}\n\n"
                       f"Built by the Agent Builder from the request:\n\n> {state['request']}\n")
    ctx.runtime.register(spec)
    ctx.run.emit("build", spec.id, "done", f"Registered {spec.name} v{spec.version} ({spec.status})",
                 agent=json.loads(spec.model_dump_json()), task_id=ctx.task.task_id)
    ctx.files_created.extend(files)
    return {"spec": json.loads(spec.model_dump_json()), "files": files}


def smoke_run(state: BuilderState, config) -> dict:
    ctx = get_ctx(config)
    spec = state["spec"]
    if spec["status"] != "active":
        ctx.node("smoke_run", "Skipped (agent not active)")
        return {"smoke": {"skipped": True}}
    ctx.node("smoke_run", f"Smoke-testing {spec['name']} on an example task")
    task = AgentTask(task_id=uuid.uuid4().hex[:8], agent_id=spec["id"],
                     instruction=spec["config"].get("example_task") or state["request"], run_id=ctx.run.run_id,
                     parent_agent=ctx.spec.id, depth=ctx.task.depth + 1)
    try:
        rep = ctx.runtime.run_agent(task, ctx.run)
        rep = rep.model_dump() if hasattr(rep, "model_dump") else dict(rep)
        return {"smoke": {"status": rep.get("status"), "summary": rep.get("summary", "")[:400]}}
    except Exception as e:  # noqa: BLE001
        return {"smoke": {"status": "failed", "summary": str(e)[:400]}}


def finish(state: BuilderState, config) -> dict:
    ctx = get_ctx(config)
    ctx.node("report", "Build report")
    spec = state.get("spec") or state["design"]
    tr = state.get("test_results", {})
    ok_ = spec.get("status") == "active"
    status = "success" if ok_ else ("partial" if spec.get("status") == "draft" and tr.get("ok") else "failed")
    summary = (f"{'Created' if ok_ else 'Built (not activated)'} {spec['name']} v{spec.get('version', '1.0')} "
               f"[{spec['graph']} workflow; status {spec.get('status')}]. Tests {tr.get('passed', 0)}/"
               f"{tr.get('passed', 0) + tr.get('failed', 0)} passed after {state.get('attempts', 0)} fix round(s).")
    result = {"agent": spec, "tests": tr, "security": state.get("security"), "smoke": state.get("smoke"),
              "reused_agents": spec.get("uses", []), "similar_existing": state.get("similar", [])[:5]}
    artifacts = [{"kind": "file", "title": "manifest", "content": json.dumps(spec, indent=2, default=str)}]
    if state.get("code"):
        artifacts.append({"kind": "file", "title": "logic.py", "content": state["code"]})
    errs = state.get("validation", {}).get("errors", []) + \
        [p for d in tr.get("details", []) for p in d.get("problems", [])]
    return {"report": ctx.report(summary, result=result, status=status, artifacts=artifacts,
                                 errors=errs if not ok_ else [], files_created=state.get("files", []),
                                 recommendations=[f"Try it: {spec.get('config', {}).get('example_task', '')[:120]}"]
                                 if ok_ else ["Review the draft in the Builder page and rebuild"])}


# ------------------------------------------------------------------------------------------- routing
def _max(state: BuilderState) -> int:
    return state.get("max_attempts", cfg.MAX_BUILD_ATTEMPTS)


def after_validation(state: BuilderState) -> str:
    if state["validation"]["ok"]:
        return "run_tests"
    return "debug" if state.get("attempts", 0) < _max(state) else "security_review"


def after_tests(state: BuilderState) -> str:
    if state["test_results"]["ok"]:
        return "security_review"
    return "debug" if state.get("attempts", 0) < _max(state) else "security_review"


def after_approval(state: BuilderState) -> str:
    return "register"  # approved -> active; rejected/failed -> saved as draft/failed so it can be edited & rebuilt


@archetype("builder", "Agent Builder: spec → design → code → tests → validate/debug → approve → register")
def build(spec):
    g = StateGraph(BuilderState)
    nodes = [("understand_spec", understand_spec), ("inspect_registry", inspect_registry),
             ("select_components", select_components), ("design", design), ("generate_prompts", generate_prompts),
             ("generate_code", generate_code), ("generate_tests", generate_tests),
             ("static_validation", static_validation), ("run_tests", run_tests), ("debug", debug),
             ("security_review", security_review), ("approval_gate", approval_gate), ("register", register),
             ("smoke_run", smoke_run), ("report", finish)]
    for n, fn in nodes:
        g.add_node(n, fn)
    g.add_edge(START, "understand_spec")
    for a, b in [("understand_spec", "inspect_registry"), ("inspect_registry", "select_components"),
                 ("select_components", "design"), ("design", "generate_prompts"),
                 ("generate_prompts", "generate_code"), ("generate_code", "generate_tests"),
                 ("generate_tests", "static_validation"), ("debug", "static_validation"),
                 ("security_review", "approval_gate"), ("register", "smoke_run"), ("smoke_run", "report")]:
        g.add_edge(a, b)
    g.add_conditional_edges("static_validation", after_validation, ["run_tests", "debug", "security_review"])
    g.add_conditional_edges("run_tests", after_tests, ["security_review", "debug"])
    g.add_conditional_edges("approval_gate", after_approval, ["register"])
    g.add_edge("report", END)
    return g
